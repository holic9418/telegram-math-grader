# -*- coding: utf-8 -*-
"""과목별 설정. Railway 환경변수 SUBJECT(math/english/korean)로 선택한다.

과목마다 다른 것:
  - display : 안내문·보고서에 쓰는 과목 표시 이름
  - schedules : {반: [수업요일idx,...]}  (비우면 출석부 파일 날짜에서 자동 추론)
  - times : {반: {요일idx(str): 'HH:MM'}}  출석 미입력 알림 시각 (비우면 알림 명령으로 설정)

수강생 명단은 출석부 엑셀(시드)에서, 담당 선생님은 '담당' 명령으로 지정하므로
여기엔 넣지 않는다. 새 과목은 이 파일에 항목만 추가하면 된다.
"""
import attendance_core as ac

SUBJECTS = {
    # 수학 — 기존 값 그대로 사용
    "math": {
        "display": "Zest 수학과",
        "schedules": ac.DEFAULT_SCHEDULES,
        "times": ac.DEFAULT_CLASS_TIMES,
    },
    # 영어 — 분반·시간은 배포 후 '일정'/'알림' 명령 또는 아래에 채워 넣기
    "english": {
        "display": "Zest 영어과",
        "schedules": {},
        "times": {},
    },
    # 국어 (시간표: 모두 오후. 알림 = 수업종료+15분)
    "korean": {
        "display": "Zest 국어과",
        "schedules": {
            "초3": [0, 4], "초5": [0, 4], "초6": [1, 3], "중1": [0, 4],
            "중2": [0, 4], "중3": [0, 4], "고1": [1, 3], "고2": [1, 3],
        },
        "times": {
            "초3": {"0": "15:15", "4": "15:15"},   # 월금 2~3
            "초5": {"0": "16:15", "4": "16:15"},   # 월금 3~4
            "초6": {"1": "16:15", "3": "16:15"},   # 화목 3~4
            "중1": {"0": "18:15", "4": "18:15"},   # 월금 4~6
            "중2": {"0": "22:15", "4": "22:15"},   # 월금 8~10
            "중3": {"0": "20:15", "4": "20:15"},   # 월금 6~8
            "고1": {"1": "20:15", "3": "20:15"},   # 화목 6~8
            "고2": {"1": "22:15", "3": "22:15"},   # 화목 8~10
        },
    },
}


def get(name):
    """과목 설정 반환. 모르는 이름이면 math."""
    return SUBJECTS.get((name or "math").strip().lower(), SUBJECTS["math"])
